// Backtracking helper for N-Queens.
// Returns the first up to 3 solutions in lexicographic order.
// totalSolutions is set to the total number of valid placements.
std::vector<std::vector<int>> nQueensSolutions(int n, int& totalSolutions) {
    totalSolutions = 0;
    std::vector<std::vector<int>> result;
    if (n < 1) return result;

    // placement[r] = column of queen in row r (1-based), for r in [1..n]
    std::vector<int> placement(n + 1, 0);
    // Attack sets: colUsed[c], diagUsed[main: (row-col)+n], antiDiagUsed[(row+col)]
    std::vector<bool> colUsed(n + 1, false);
    std::vector<bool> diagUsed(2 * n + 1, false);   // index = row - col + n
    std::vector<bool> antiDiagUsed(2 * n + 1, false); // index = row + col

    // Recursive lambda defined via std::function, but we can use a helper function with captures.
    // For simplicity, use a local recursive function pointer via std::function.
    // However, to avoid heavy std::function, we use a nested lambda with a self-capture pattern (C++14).
    auto backtrack = [&](auto&& self, int row) -> void {
        if (row > n) {
            ++totalSolutions;
            if (result.size() < 3) {
                result.emplace_back(placement.begin() + 1, placement.end());
            }
            return;
        }

        for (int col = 1; col <= n; ++col) {
            int diag = row - col + n;
            int anti = row + col;
            if (colUsed[col] || diagUsed[diag] || antiDiagUsed[anti]) {
                continue;
            }

            placement[row] = col;
            colUsed[col] = true;
            diagUsed[diag] = true;
            antiDiagUsed[anti] = true;

            self(self, row + 1);

            // Backtrack
            colUsed[col] = false;
            diagUsed[diag] = false;
            antiDiagUsed[anti] = false;
            placement[row] = 0;
        }
    };

    backtrack(backtrack, 1);
    return result;
}

// The problem is the classic N-Queens. We use backtracking: place a queen row by row, starting from row 1, and for each row, try each column from 1 to n. Before placing, we check whether the column and both diagonals are already attacked by previously placed queens. We can maintain three arrays or sets: one for columns, one for the main diagonal (row-col index), and one for the anti-diagonal (row+col index). To generate solutions in lexicographic order, simply iterate columns from 1 to n. When a full solution is found (row > n), increment the total count, and if the count is less than or equal to 3, store a copy of the current placement. Time complexity is O(n!) in the worst case due to the number of placements, but pruning reduces this; for n ≤ 14 it is acceptable. Space complexity is O(n) for the placement array and O(n) for the attack sets, plus O(3n) for storing up to 3 solutions, so overall O(n) auxiliary space. Edge cases: n = 1 returns one solution `[1]`; n = 0 or negative returns empty. For n = 2,3 there are no solutions, so totalSolutions = 0 and the returned vector is empty.
