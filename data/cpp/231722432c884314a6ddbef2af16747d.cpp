// Given an integer `n` (where 1 ≤ n ≤ 14), write a C++ function `vector<vector<int>> nQueensSolutions(int n)` that returns the first up to 3 distinct solutions to the classic N-Queens problem, where you place `n` queens on an `n × n` chessboard such that no two queens attack each other (no two share the same row, column, or diagonal). The function should output a vector of solutions, where each solution is a vector of length `n` (index 1..n) giving the column position (1-based) of the queen in each row. Additionally, the function must return a count of all valid solutions, but since returning both a count and the first 3 solutions is awkward in a single return type, design the function to return `vector<vector<int>>` containing at most 3 solutions, and use a reference parameter `int& totalSolutions` to output the total number of valid solutions. The returned solutions should be in lexicographic order of their row-wise column placements (as generated by a standard backtracking search). If there are fewer than 3 solutions, return all of them in order. If `n` is invalid (e.g., less than 1), return an empty vector and set `totalSolutions` to 0.

