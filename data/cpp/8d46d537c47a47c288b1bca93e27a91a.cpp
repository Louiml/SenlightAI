int main() {
    // Base case: a single tetrahedron has 4 triangles.
    assert(count_triangles(0) == 4);
    // One subdivision: 4 tetrahedrons each with 4 triangles = 16.
    assert(count_triangles(1) == 16);
    // Two subdivisions: 4^3 = 64.
    assert(count_triangles(2) == 64);
    // Verify a moderate depth: depth 3 -> 4^4 = 256.
    assert(count_triangles(3) == 256);
    // Larger depth: depth 10 -> 4^11 = 4,194,304.
    assert(count_triangles(10) == 4194304ULL);
    // Edge: depth 30 -> 2^62 = 4,611,686,018,427,387,904.
    assert(count_triangles(30) == 4611686018427387904ULL);
    // Negative depth should throw.
    bool threw = false;
    try {
        count_triangles(-1);
    } catch (const std::invalid_argument&) {
        threw = true;
    }
    assert(threw);
    // Depth 31 causes overflow.
    threw = false;
    try {
        count_triangles(31);
    } catch (const std::overflow_error&) {
        threw = true;
    }
    assert(threw);
}
