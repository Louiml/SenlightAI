// Edge cases: m=0 gives 4; m very large could overflow a 32-bit int, so use `long long` or `uint64_t`. For m=30, 4^31 is about 4.6e18, which fits in 64-bit. For m=31 it overflows 64-bit? 4^32 = 2^64, which overflows signed 64-bit (max ~9.22e18). So we can cap at m=30 or use unsigned. The task says up to 30, so fine. The recursive approach is O(m) depth but number of calls is 4^m, which is huge. So we should compute directly using exponentiation, not recursion. The analysis will mention that a direct formula is O(log m) or O(1) using bit shift since 4^(m+1) = 2^(2*(m+1)). 
