// Implementation: `std::uint64_t countTriangles(int m)` returns `1ULL << (2*(m+1))` when m >= 0. But for m=30, 2*(30+1)=62, so 2^62 fits in 64-bit. For m=31, 2^64 overflow. So we check that m <= 30. If m < 0, return 0? The task says non-negative, so no need. 
