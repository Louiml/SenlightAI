#include <cstdint>
#include <stdexcept>

// Count the total number of triangles generated by subdividing a tetrahedron
// recursively for `depth` levels. Each subdivision replaces one tetrahedron
// with four smaller tetrahedrons; the base case (depth 0) draws 4 triangular faces.
std::uint64_t count_triangles(int depth) {
    if (depth < 0) {
        throw std::invalid_argument("depth must be non-negative");
    }
    // Each level multiplies triangle count by 4. For depth d, total = 4^(d+1).
    // Since 4 = 2^2, we can use a bit shift on a 64-bit integer.
    // Maximum depth that fits in uint64_t is 30 (since 2^(2*(30+1)) = 2^62).
    if (depth > 30) {
        throw std::overflow_error("depth too large for 64-bit result");
    }
    return std::uint64_t{1} << (2 * (depth + 1));
}

#include <cstdint>
#include <cassert>
#include <stdexcept>

