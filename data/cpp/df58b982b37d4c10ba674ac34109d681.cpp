    auto r6 = findAllPathsInMaze(m6, 3);
    assert(r6.size() == 1);
    assert(r6[0] == "DDDR");

    // Test 8: 2x2 with only right then down
    std::vector<std::vector<int>> m7 = {{1, 1}, {0, 1}};
    auto r7 = findAllPathsInMaze(m7, 2);
    assert(r7.size() == 1);
    assert(r7[0] == "RD");

    // Test 9: 2x2 with only down then right
    std::vector<std::vector<int>> m8 = {{1, 0}, {1, 1}};
    auto r8 = findAllPathsInMaze(m8, 2);
