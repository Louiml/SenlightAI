#include <vector>
#include <string>
#include <functional>

// Find all paths from (0,0) to (n-1,n-1) in a maze of 1s and 0s.
// Moves: D, L, R, U. Output is lexicographically sorted by move order.
std::vector<std::string> findAllPathsInMaze(const std::vector<std::vector<int>>& m, int n) {
    std::vector<std::string> ans;
    if (n == 0 || m[0][0] == 0 || m[n-1][n-1] == 0) {
        return ans;
    }

    std::vector<std::vector<int>> visited(n, std::vector<int>(n, 0));
    std::string path;

    // Recursive lambda for backtracking
    std::function<void(int, int)> dfs = [&](int x, int y) {
        if (x == n - 1 && y == n - 1) {
            ans.push_back(path);
            return;
        }
        visited[x][y] = 1;

        // Move order: D, L, R, U for lexicographical order
        int dx[4] = {1, 0, 0, -1};
        int dy[4] = {0, -1, 1, 0};
        char dir[4] = {'D', 'L', 'R', 'U'};

        for (int i = 0; i < 4; ++i) {
            int nx = x + dx[i];
            int ny = y + dy[i];
            if (nx >= 0 && nx < n && ny >= 0 && ny < n &&
                m[nx][ny] == 1 && visited[nx][ny] == 0) {
                path.push_back(dir[i]);
                dfs(nx, ny);
                path.pop_back();
            }
        }

        visited[x][y] = 0;
    };

    dfs(0, 0);
    return ans;
}
// The problem is a classic backtracking search on a grid. The main function initializes a visited matrix (`pathcover`) of zeros, then starts the recursive `solve` from `(0,0)`. The base case triggers when the coordinate equals `(n-1, n-1)`, appending the current path string to the answer. Before recursing, the current cell is marked visited; after all four directional attempts, it is unmarked to allow other paths. The move order is deliberately D, L, R, U to match lexicographical ordering. The safety check in the given code has bugs (e.g., `y == 0 && y < n` should be `y >= 0 && y < n`, `m[x][y] = 1` is assignment not comparison), so the reference solution fixes these. Important edge cases: if the start is blocked, return empty; if `n=1` and start is unblocked, return `[""]` (empty path); if no moves are possible due to blocks or visited cells, backtrack. Time complexity is O(4^(n^2)) in the worst case for the number of paths, but in practice it's bounded by the number of distinct simple paths. Space complexity is O(n^2) for the visited matrix and recursion stack, plus O(path_length) for storing each path string.
