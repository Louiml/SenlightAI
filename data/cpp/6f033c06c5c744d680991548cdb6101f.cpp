/*
Given a company's organizational hierarchy where each employee (except the big boss) reports to exactly one direct superior, write a C++ function `vector<int> buildEulerTour(int n, const vector<int>& bossOf)` that takes the number of employees `n` and an array `bossOf` of length `n` (where `bossOf[i]` is the 1-based index of the direct boss of employee `i`, or `-1` if `i` is the big boss), and returns the Euler tour sequence of employee indices (1-based) generated by a depth-first pre-order traversal with post-order backtracking. The traversal starts at the big boss, visits each employee in increasing order of their employee index among their direct subordinates, and after finishing a subtree, appends the current node again. The output must be a vector of 1-based employee IDs in the exact order produced by this traversal.
*/
#include <vector>

// Build the Euler tour of a rooted tree represented by bossOf (1-based boss, -1 for root).
// Returns a vector of 1-based employee IDs in DFS pre-order with post-order backtracking.
std::vector<int> buildEulerTour(int n, const std::vector<int>& bossOf) {
    // Build adjacency: subordinates[parent] = list of children (0-based indices)
    std::vector<std::vector<int>> subordinates(n);
    int bigBoss = -1;
    for (int i = 0; i < n; ++i) {
        if (bossOf[i] == -1) {
            bigBoss = i;
        } else {
            subordinates[bossOf[i] - 1].push_back(i);
        }
    }

    std::vector<int> euler_tour;
    // Recursive DFS
    std::function<void(int)> dfs = [&](int curr) {
        euler_tour.push_back(curr + 1); // output 1-based
        for (int child : subordinates[curr]) {
            dfs(child);
            euler_tour.push_back(curr + 1); // post-order revisit
        }
    };

    dfs(bigBoss);
    return euler_tour;
}
