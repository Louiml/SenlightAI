using int64 = long long;
using int128 = __int128_t;

// Extended Euclidean algorithm: returns gcd(a,b) and sets x,y such that a*x + b*y = gcd
int64 extgcd(int64 a, int64 b, int64 &x, int64 &y) {
    if (b == 0) {
        x = 1;
        y = 0;
        return a;
    }
    int64 x1, y1;
    int64 g = extgcd(b, a % b, x1, y1);
    x = y1;
    y = x1 - (a / b) * y1;
    return g;
}

// CRT for two congruences x ≡ a1 (mod m1), x ≡ a2 (mod m2), returns x or -1 if impossible
int64 crt2(int64 a1, int64 m1, int64 a2, int64 m2) {
    int64 p, q;
    int64 g = extgcd(m1, m2, p, q);
    if ((a2 - a1) % g != 0) return -1;
    int64 lcm = m1 / g * m2;
    // Careful with overflow: use __int128
    int128 res = (int128)a1 + (int128)m1 * (int128)p * (int128)((a2 - a1) / g);
    res %= lcm;
    if (res < 0) res += lcm;
    return (int64)res;
}

// Prime sieve up to max value
std::vector<int> primes;
void sieve(int maxN) {
    std::vector<bool> isPrime(maxN + 1, true);
    isPrime[0] = isPrime[1] = false;
    for (int i = 2; i <= maxN; ++i) {
        if (isPrime[i]) {
            primes.push_back(i);
            if ((int64)i * i <= maxN) {
                for (int64 j = (int64)i * i; j <= maxN; j += i)
                    isPrime[(int)j] = false;
            }
        }
    }
}

// Solve system of congruences using CRT with prime-power factorization
int64 solveCRT(const std::vector<int64>& a, const std::vector<int64>& mod) {
    // Map from prime to (remainder, prime_power)
    std::map<int64, std::pair<int64,int64>> primeMap;
    for (size_t i = 0; i < a.size(); ++i) {
        int64 n = mod[i];
        // factor n
        for (int p : primes) {
            if ((int64)p * p > n) break;
            if (n % p == 0) {
                int64 pow = 1;
                while (n % p == 0) {
                    n /= p;
                    pow *= p;
                }
                // Check consistency
                if (primeMap.count(p)) {
                    auto& [oldRem, oldPow] = primeMap[p];
                    // ensure pow is the larger power
                    if (pow > oldPow) {
                        std::swap(oldRem, (int64&)a[i]);
                        std::swap(oldPow, pow);
                    }
                    // Check remainder compatibility on the smaller power
                    if ((oldRem - a[i]) % pow != 0)
                        return -1;
                } else {
                    primeMap[p] = {a[i], pow};
                }
            }
        }
        if (n > 1) {
            int64 p = n;
            if (primeMap.count(p)) {
                auto& [oldRem, oldPow] = primeMap[p];
                // n is prime itself, pow = n
                if ((oldRem - a[i]) % n != 0)
                    return -1;
            } else {
                primeMap[p] = {a[i], n};
            }
        }
    }
    // Now collect residues and moduli
    std::vector<int64> residues, moduli;
    for (const auto& [p, pr] : primeMap) {
        residues.push_back(pr.first);
        moduli.push_back(pr.second);
    }
    // Combine using CRT
    int64 curMod = 1, curRes = 0;
    for (size_t i = 0; i < moduli.size(); ++i) {
        int64 newRes = crt2(curRes, curMod, residues[i], moduli[i]);
        if (newRes < 0) return -1;
        curRes = newRes;
        curMod = moduli[i] / std::__gcd(moduli[i], curMod) * curMod;
    }
    return curRes;
}

// Main function: find smallest common step, or -1
int64 findCommonStep(int m, int64 h1, int64 a1, int64 x1, int64 y1,
                     int64 h2, int64 a2, int64 x2, int64 y2) {
    // Precompute primes up to 1e6+10
    if (primes.empty()) sieve(1123456);

    // Data for sequence 1 and 2
    std::vector<int> memo1(2*m+5, -1), memo2(2*m+5, -1);
    int first1 = -1, period1 = -1, prePeriod1 = -1;
    int first2 = -1, period2 = -1, prePeriod2 = -1;

    int64 h = h1;
    for (int i = 0; i < 2*m; ++i) {
        if (memo1[h] >= 0) {
            if (period1 == -1) {
                period1 = i - memo1[h];
                prePeriod1 = memo1[h];
            }
        }
        memo1[h] = i;
        if (h == a1 && first1 == -1) first1 = i;
        h = (x1 * h % m + y1) % m;
    }

    h = h2;
    for (int i = 0; i < 2*m; ++i) {
        if (memo2[h] >= 0) {
            if (period2 == -1) {
                period2 = i - memo2[h];
                prePeriod2 = memo2[h];
            }
        }
        memo2[h] = i;
        if (h == a2 && first2 == -1) first2 = i;
        h = (x2 * h % m + y2) % m;
    }

    // If target never appears
    if (first1 == -1 || first2 == -1) return -1;

    // If period is 0 (target only in pre-period)
    if (period1 == -1) period1 = 0;
    if (period2 == -1) period2 = 0;

    // Build congruences
    std::vector<int64> residues, moduli;
    if (period1 > 0) {
        residues.push_back(first1);
        moduli.push_back(period1);
    }
    if (period2 > 0) {
        residues.push_back(first2);
        moduli.push_back(period2);
    }

    int64 solution = 0;
    if (moduli.empty()) {
        // Both targets occur only once in pre-period
        if (first1 == first2) solution = first1;
        else return -1;
    } else {
        solution = solveCRT(residues, moduli);
        if (solution < 0) return -1;
    }

    // Adjust to meet pre-period requirement
    int64 mn = std::max(prePeriod1, prePeriod2);
    if (solution < mn) {
        int64 lcm = 1;
        for (int64 mod : moduli) lcm = lcm / std::__gcd(lcm, mod) * mod;
        if (lcm == 0) lcm = 1; // only one congruence or none
        solution += ((mn - solution + lcm - 1) / lcm) * lcm;
    }

    // Validate solution (optional but safe)
    // For each sequence, verify that at step solution we have target
    int64 h1s = h1, h2s = h2;
    if (solution > (int64)1e9) {
        // For very large solution, just trust CRT (but we could check with modular exponentiation if needed)
        // Here we just return since m <= 1e6 and periods <= m, solution <= lcm <= m^2
    }
    // Quick verify by simulation if solution <= 2*m (i.e., within initial scan)
    if (solution < (int64)2*m) {
        h = h1;
        for (int i = 0; i < (int)solution; ++i) {
            if (h != a1) h = (x1 * h % m + y1) % m;
            else break;
        }
        if (h != a1) return -1;
        h = h2;
        for (int i = 0; i < (int)solution; ++i) {
            if (h != a2) h = (x2 * h % m + y2) % m;
            else break;
        }
        if (h != a2) return -1;
    }

    return solution;
}
